namespace Yepr\Component\Gengen\Administrator\Generator;

use Yepr\Gen\Core\Rule\RuleSet;

// phpcs:disable PSR1.Files.SideEffects
\defined('_JEXEC') or die;
// phpcs:enable PSR1.Files.SideEffects

/**
 * A generator package, read back into a model: the Import button.
 *
 * Three kinds of zip reach the button, and they say different amounts about
 * the generator in them:
 *
 * - **One this component generated, since 0.6.** It holds `model.json`, the
 *   form data itself, so reading it is reading the model. A round trip is
 *   exact: groups, summaries, output path and namespace all come back.
 * - **One without `model.json`**: generated by an older Generator Generator, or
 *   one of the Extension Generator's own packages zipped up, such as
 *   `ledgerlang.package.json` with `ledgerlang.rules.json`. The rules are in
 *   the rule file, and everything else is looked for: in a modelling manifest
 *   if one came with it (the `*.manifest.json` that `import-generator.php`
 *   reads), else in `generator.json`, else guessed. The guesses are said, in
 *   `notes`, so nobody mistakes a guess for what the package said.
 * - **Something else**, which is refused with a sentence that says why.
 *
 * Nothing here touches the site. Reading and checking come first and storing
 * comes after, so a refused import leaves nothing behind - the same order the
 * metalanguage import and the Extension Generator's generator import keep.
 *
 * Only data is read. The classes in a generated package are wiring, made again
 * from the model whenever somebody presses Generate, and no PHP from an upload
 * is ever loaded.
 *
 * @since  0.6.0
 */
final class ImportedGenerator
{
    /**
     * Where the model came from: `model.json`, read as it is.
     *
     * @since  0.6.0
     */
    public const FROM_MODEL = 'model';

    /**
     * Where the model came from: the rule file, with what a manifest said about the rest.
     *
     * @since  0.6.0
     */
    public const FROM_RULES = 'rules';

    /**
     * Constructor.
     *
     * @param   GeneratorDefinition  $definition           The generator, ready to store as form data.
     * @param   string               $metalanguageKey      The language the package says it is for, '' for none.
     * @param   string               $metalanguageVersion  That language's version, '' for any.
     * @param   string               $source               `FROM_MODEL` or `FROM_RULES`.
     * @param   string[]             $notes                What was guessed rather than read.
     *
     * @since   0.6.0
     */
    private function __construct(
        public readonly GeneratorDefinition $definition,
        public readonly string $metalanguageKey,
        public readonly string $metalanguageVersion,
        public readonly string $source,
        public readonly array $notes
    ) {
    }

    /**
     * Read a zip, or say why it is not a generator package.
     *
     * @param   string  $zip  Path to the uploaded file.
     *
     * @return  self
     *
     * @throws  \RuntimeException  With a sentence a person can act on.
     *
     * @since   0.6.0
     */
    public static function fromZip(string $zip): self
    {
        $archive = new \ZipArchive();

        if (!is_file($zip) || $archive->open($zip) !== true) {
            throw new \RuntimeException('This is not a zip file.');
        }

        try {
            $files = [];

            for ($index = 0; $index < $archive->numFiles; $index++) {
                $name = (string) $archive->getNameIndex($index);

                if ($name !== '' && !str_ends_with($name, '/')) {
                    $files[$name] = (string) $archive->getFromIndex($index);
                }
            }

            return self::fromFiles($files);
        } finally {
            $archive->close();
        }
    }

    /**
     * Read the files of a package, by their paths inside it.
     *
     * The zip is only the envelope, so the reading is done on a plain map of
     * paths to contents. That is also what lets the tests hand it a package
     * without writing one to disk first.
     *
     * @param   array<string, string>  $files  Path inside the package => contents.
     *
     * @return  self
     *
     * @throws  \RuntimeException  With a sentence a person can act on.
     *
     * @since   0.6.0
     */
    public static function fromFiles(array $files): self
    {
        // What the package says about itself: Gen-gen's `generator.json`, or a
        // manifest the Extension Generator ships beside a rule file.
        $manifest = self::json($files, GeneratorManifest::FILE)
            ?? self::json($files, self::onlyOne($files, '.package.json'));

        if ($manifest !== null) {
            $format = (int) ($manifest['format'] ?? 0);

            if ($format > GeneratorManifest::FORMAT) {
                throw new \RuntimeException(
                    'This package is format ' . $format . '; this Generator Generator reads formats up to '
                    . GeneratorManifest::FORMAT . '. Update it and import the package again.'
                );
            }
        }

        $language = \is_array($manifest['metalanguage'] ?? null) ? $manifest['metalanguage'] : [];
        $key      = trim((string) ($language['key'] ?? ''));
        $version  = trim((string) ($language['version'] ?? ''));

        $model = self::json($files, GeneratorManifest::MODEL);

        if ($model !== null) {
            return new self(self::fromModel($model), $key, $version, self::FROM_MODEL, []);
        }

        return self::fromRuleFile($files, $manifest ?? [], $key, $version);
    }

    /**
     * Everything the generator names that the installed target does not publish.
     *
     * The same check the forms make possible and the Extension Generator makes
     * at its import: every selector, derivation and template a rule names has
     * to be in the target's vocabulary. A rule may also select a concept of the
     * metalanguage the generator is written for, so the caller passes those
     * concepts in when the language is on the site.
     *
     * @param   VocabularyLibrary  $library   The targets this site publishes.
     * @param   string[]           $concepts  Concept names a rule may select as well.
     *
     * @return  string[]  Empty when the generator can be imported.
     *
     * @since   0.6.0
     */
    public function problems(VocabularyLibrary $library, array $concepts = []): array
    {
        $target = $this->definition->target;

        if (!$library->has($target)) {
            $found = $library->targets();

            return [
                'It is for the target "' . $target . '", and nothing on this site publishes a vocabulary'
                . ' for it. Found: '
                . ($found === [] ? '(none)' : implode(', ', $found)) . '.',
            ];
        }

        $rules = $this->definition->rules();

        if (\count($rules) === 0) {
            return ['The generator has no rules.'];
        }

        $vocabulary = $library->get($target);

        return ($concepts === [] ? $vocabulary : $vocabulary->withConcepts($concepts))->problems($rules);
    }

    /**
     * The model, from `model.json`.
     *
     * @param   array<string, mixed>  $model  The decoded form data.
     *
     * @return  GeneratorDefinition
     *
     * @since   0.6.0
     */
    private static function fromModel(array $model): GeneratorDefinition
    {
        $definition = GeneratorDefinition::fromFormData($model);

        if (trim($definition->name) === '' || trim($definition->target) === '') {
            throw new \RuntimeException(
                GeneratorManifest::MODEL . ' must say the generator\'s name and its target.'
            );
        }

        self::readable(static fn () => $definition->rules(), GeneratorManifest::MODEL);

        return $definition;
    }

    /**
     * The model, from the rule file and whatever came with it.
     *
     * @param   array<string, string>  $files     The package's files.
     * @param   array<string, mixed>   $manifest  `generator.json` or `*.package.json`, or empty.
     * @param   string                 $key       The language it is for.
     * @param   string                 $version   That language's version.
     *
     * @return  self
     *
     * @since   0.6.0
     */
    private static function fromRuleFile(array $files, array $manifest, string $key, string $version): self
    {
        // The modelling manifest: what `import-generator.php` builds the
        // committed models from. It is the one file that knows the groups'
        // summaries, the output path and the namespace.
        $modelling = self::json($files, self::onlyOne($files, '.manifest.json')) ?? [];

        $rulesPath = self::ruleFile(
            $files,
            (string) ($manifest['rules'] ?? $modelling['rules'] ?? '')
        );

        $target = trim((string) ($manifest['target'] ?? $modelling['target'] ?? ''));

        // A rule file on its own is the Extension Generator's way of shipping a
        // target's own generator: `joomla6.rules.json` is the rules of the
        // target `joomla6`.
        if ($target === '' && $manifest === [] && $modelling === []) {
            $target = basename($rulesPath, '.rules.json');
        }

        if ($target === '') {
            throw new \RuntimeException('The package does not say which target its generator is for.');
        }

        $rules = self::readable(static fn () => RuleSet::fromJson($files[$rulesPath]), $rulesPath);

        $name = trim((string) ($modelling['generator_name'] ?? $manifest['name'] ?? ''));
        $name = $name !== '' ? $name : $target;

        $notes = [];

        if (\is_array($modelling['group'] ?? null)) {
            $groups = array_values(array_filter($modelling['group'], 'is_array'));
        } elseif (\is_array($manifest['groups'] ?? null)) {
            $groups = array_values(array_filter($manifest['groups'], 'is_array'));
        } else {
            $groups  = self::groupsByPrefix($rules);
            $notes[] = 'The package does not say which classes its rules belong to, so there is one group per'
                . ' rule-id prefix. Check them on the Rules tab, and tick "emits" for a group that writes'
                . ' files of its own.';
        }

        $outputPath = trim((string) ($modelling['output_path'] ?? ''));

        // Gen-gen's manifest names the rule file as `<output path>/Rules/<target>.rules.json`
        // (see GeneratorDefinition::ruleFilePath()), so the output path can be
        // read back off it.
        if ($outputPath === '' && preg_match('#^(.+)/Rules/[^/]+\.rules\.json$#', $rulesPath, $match) === 1) {
            $outputPath = $match[1];
        }

        $namespace = trim((string) ($modelling['php_namespace'] ?? ''));

        if ($outputPath === '' || $namespace === '') {
            $notes[] = 'The package does not say where the generator\'s own source goes or which namespace'
                . ' its classes are in. Fill those in before generating.';
        }

        $definition = GeneratorDefinition::fromRuleSet(
            $name,
            $target,
            $rules,
            $groups,
            $outputPath,
            $namespace,
            trim((string) ($modelling['extends'] ?? $manifest['extends'] ?? ''))
        );

        return new self($definition, $key, $version, self::FROM_RULES, $notes);
    }

    /**
     * Which file is the rule file.
     *
     * The path the manifest names, when it is in the package. Else a file of
     * that name anywhere in it, because a manifest the Extension Generator
     * ships names its rule file by name only. Else the one `*.rules.json`
     * there is.
     *
     * @param   array<string, string>  $files  The package's files.
     * @param   string                 $named  What a manifest says, '' for nothing.
     *
     * @return  string  A path that is in `$files`.
     *
     * @since   0.6.0
     */
    private static function ruleFile(array $files, string $named): string
    {
        if ($named !== '') {
            if (isset($files[$named])) {
                return $named;
            }

            foreach (array_keys($files) as $path) {
                if (basename($path) === basename($named)) {
                    return $path;
                }
            }

            throw new \RuntimeException('The rule file the package names, "' . $named . '", is not in it.');
        }

        $found = array_values(array_filter(
            array_keys($files),
            static fn (string $path): bool => str_ends_with($path, '.rules.json')
        ));

        if (\count($found) !== 1) {
            throw new \RuntimeException(
                'This is not a generator package: it has no ' . GeneratorManifest::FILE . ', no '
                . GeneratorManifest::MODEL . ' and '
                . (\count($found) === 0 ? 'no rule file' : 'more than one rule file')
                . '. Generate it with the Generator Generator, or zip a rule file with its manifest.'
            );
        }

        return $found[0];
    }

    /**
     * One group per rule-id prefix, in the order the rules first use it.
     *
     * The prefix is the id without its last part, and at most its first two
     * parts: `admin.mvc.index.model` is in `admin.mvc.`, `component.manifest`
     * in `component.`. For the Joomla 6 rules that is exactly how the
     * Extension Generator slices them. The class is the prefix in StudlyCase.
     *
     * @param   RuleSet  $rules  The rules.
     *
     * @return  array<int, array<string, mixed>>
     *
     * @since   0.6.0
     */
    private static function groupsByPrefix(RuleSet $rules): array
    {
        $groups = [];

        foreach ($rules as $rule) {
            $parts = explode('.', $rule->id);

            if (\count($parts) < 2) {
                $prefix = $rule->id;
            } else {
                $prefix = implode('.', \array_slice($parts, 0, min(2, \count($parts) - 1))) . '.';
            }

            if (isset($groups[$prefix])) {
                continue;
            }

            $class = implode('', array_map(
                'ucfirst',
                preg_split('/[^A-Za-z0-9]+/', $prefix, -1, \PREG_SPLIT_NO_EMPTY) ?: []
            ));

            $groups[$prefix] = [
                'class'   => $class !== '' ? $class : 'Rules',
                'prefix'  => $prefix,
                'summary' => '',
                'emits'   => false,
            ];
        }

        return array_values($groups);
    }

    /**
     * Run a read, and turn what a malformed rule throws into one sentence.
     *
     * @template T
     *
     * @param   callable(): T  $read   The read.
     * @param   string         $where  Which file it reads.
     *
     * @return  T
     *
     * @since   0.6.0
     */
    private static function readable(callable $read, string $where): mixed
    {
        try {
            return $read();
        } catch (\Throwable $e) {
            throw new \RuntimeException('The rules in ' . $where . ' cannot be read: ' . $e->getMessage(), 0, $e);
        }
    }

    /**
     * A JSON object out of the package, or null when the file is not there.
     *
     * @param   array<string, string>  $files  The package's files.
     * @param   ?string                $path   The file, or null for none.
     *
     * @return  ?array<string, mixed>
     *
     * @since   0.6.0
     */
    private static function json(array $files, ?string $path): ?array
    {
        if ($path === null || !isset($files[$path])) {
            return null;
        }

        $data = json_decode($files[$path], true);

        if (!\is_array($data)) {
            throw new \RuntimeException(basename($path) . ' is not valid JSON.');
        }

        return $data;
    }

    /**
     * The one file at the top of the package whose name ends this way, or null.
     *
     * @param   array<string, string>  $files   The package's files.
     * @param   string                 $suffix  How its name ends.
     *
     * @return  ?string
     *
     * @since   0.6.0
     */
    private static function onlyOne(array $files, string $suffix): ?string
    {
        $found = array_values(array_filter(
            array_keys($files),
            static fn (string $path): bool => !str_contains($path, '/') && str_ends_with($path, $suffix)
        ));

        return \count($found) === 1 ? $found[0] : null;
    }
}
